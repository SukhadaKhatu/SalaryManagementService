-- Salary amounts are annual base pay in the currency's minor unit (e.g. cents).
-- Apply once to a new, empty database. All supported currencies have two decimal places.
BEGIN;

CREATE TABLE countries (
    code CHAR(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
    name TEXT NOT NULL UNIQUE,
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE departments (
    id SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE employees (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL CHECK (length(trim(first_name)) > 0),
    last_name TEXT NOT NULL CHECK (length(trim(last_name)) > 0),
    email TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%@%'),
    job_title TEXT NOT NULL CHECK (length(trim(job_title)) > 0),
    department_id SMALLINT NOT NULL REFERENCES departments(id),
    country_code CHAR(2) NOT NULL REFERENCES countries(code),
    annual_salary_minor BIGINT NOT NULL CHECK (annual_salary_minor BETWEEN 0 AND 100000000000),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Applications must update the employee and insert its audit record in one transaction.
CREATE TABLE salary_changes (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    old_salary_minor BIGINT NOT NULL CHECK (old_salary_minor BETWEEN 0 AND 100000000000),
    new_salary_minor BIGINT NOT NULL CHECK (new_salary_minor BETWEEN 0 AND 100000000000),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (old_salary_minor <> new_salary_minor)
);

CREATE INDEX employees_country_idx ON employees (country_code);
CREATE INDEX employees_department_idx ON employees (department_id);
CREATE INDEX employees_name_idx ON employees (last_name, first_name, id);
CREATE INDEX salary_changes_employee_idx ON salary_changes (employee_id, changed_at DESC, id DESC);

COMMIT;
